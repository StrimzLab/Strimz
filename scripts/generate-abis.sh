#!/usr/bin/env bash
# Writes the indexer's embedded ABI files and the API relay's ABIs from the
# Foundry build. --check compares instead of writing, for CI and preflight.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/packages/contracts/out"
DEST="$ROOT/apps/indexer/internal/abi"
RELAY_FILE="$ROOT/apps/api/src/modules/relay/generated/contracts.ts"
CONTRACTS=(StrimzRegistry StrimzPayments StrimzSubscriptions StrimzAgentEscrow FeeCollector TokenWhitelist StrimzAgentRegistry TimelockController IERC20)
RELAY_ERROR_SOURCES=(StrimzPayments StrimzSubscriptions StrimzRegistry TokenWhitelist)

check=false
case "${1:-}" in
  "") ;;
  --check) check=true ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

if [ ! -d "$OUT" ]; then
  echo "missing $OUT: run arc-forge build in packages/contracts first" >&2
  exit 1
fi

target="$DEST"
if $check; then
  target="$(mktemp -d)"
  trap 'rm -rf "$target"' EXIT
fi

for c in "${CONTRACTS[@]}"; do
  src="$OUT/$c.sol/$c.json"
  [ -f "$src" ] || { echo "missing $src" >&2; exit 1; }
  jq --indent 2 '[.abi[] | select(.type == "event")]' "$src" > "$target/$c.abi.json"
done

relay_fn() {
  jq --indent 2 --arg name "$2" '[.abi[] | select(.type == "function" and .name == $name)]' "$OUT/$1.sol/$1.json"
}
error_files=()
for c in "${RELAY_ERROR_SOURCES[@]}"; do error_files+=("$OUT/$c.sol/$c.json"); done
{
  echo "// Generated by scripts/generate-abis.sh from the contract build. Do not edit."
  echo
  echo "export const payWithAuthorizationAbi = $(relay_fn StrimzPayments payWithAuthorization) as const"
  echo
  echo "export const permitAndCreateSubscriptionAbi = $(relay_fn StrimzSubscriptions permitAndCreateSubscription) as const"
  echo
  echo "export const strimzErrorsAbi = $(jq -s --indent 2 '[.[].abi[] | select(.type == "error")] | unique_by([.name, [.inputs[].type]]) | sort_by(.name)' "${error_files[@]}") as const"
} > "$target/relay-contracts.ts"

if $check; then
  drift=false
  for c in "${CONTRACTS[@]}"; do
    if ! diff -u "$DEST/$c.abi.json" "$target/$c.abi.json" > "$target/$c.diff"; then
      drift=true
      cat "$target/$c.diff"
    fi
  done
  if ! diff -u "$RELAY_FILE" "$target/relay-contracts.ts"; then
    drift=true
  fi
  if $drift; then
    echo "The generated ABI files don't match the contract build. Run scripts/generate-abis.sh and commit the result." >&2
    exit 1
  fi
  echo "generated ABI files match the contract build"
else
  mkdir -p "$(dirname "$RELAY_FILE")"
  mv "$target/relay-contracts.ts" "$RELAY_FILE"
fi
